List<Product> productsForCategory(String id) =>
    demoProducts.where((p) => p.categoryId == id).toList();
List<Product> trendingProducts(String area) => [...demoProducts]
  ..sort((a, b) => (b.margin + b.stock).compareTo(a.margin + a.stock));
List<Product> highMarginProducts() =>
    [...demoProducts]..sort((a, b) => b.margin.compareTo(a.margin));
List<String> brands() =>
    demoProducts.map((p) => p.brand).toSet().toList()..sort();
List<Product> productsByBrand(String brand) => demoProducts
    .where((p) => p.brand.toLowerCase() == brand.toLowerCase())
    .toList();
List<Product> listProducts(String type, String area) {
  switch (type) {
    case 'high-margin':
      return highMarginProducts();
    case 'local-area':
      return trendingProducts(area).where((p) => p.stock >= 20).toList();
    case 'in-demand':
    default:
      return trendingProducts(area);
  }
}
